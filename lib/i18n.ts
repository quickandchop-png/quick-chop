const LANG_STORAGE_KEY = '@quick_chop_language';

export async function getSavedLanguage(): Promise<Language> {
  const saved = await AsyncStorage.getItem(LANG_STORAGE_KEY);
  if (saved && translations[saved as Language]) return saved as Language;
  return 'en';
}

export async function saveLanguage(lang: Language): Promise<void> {
  await AsyncStorage.setItem(LANG_STORAGE_KEY, lang);
}

export function translate(lang: Language, key: string, params?: Record<string, string | number>): string {
  let text = translations[lang]?.[key] || translations.en[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}

