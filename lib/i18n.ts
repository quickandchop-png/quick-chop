export function translateProductName(name: string, lang: Language): string {
  if (lang === 'en') return name;
  const fullMatch = productNames[name]?.[lang];
  if (fullMatch) return fullMatch;
  const aliasKey = productAliases[name];
  if (aliasKey) {
    const aliasMatch = productNames[aliasKey]?.[lang];
    if (aliasMatch) return aliasMatch;
  }
  const packMatch = name.match(/^(.+?)\s+Pack$/);
  if (packMatch) {
    const base = productNames[packMatch[1]]?.[lang];
    if (base) return base;
    const packAlias = productAliases[packMatch[1]];
    if (packAlias) {
      const packAliasMatch = productNames[packAlias]?.[lang];
      if (packAliasMatch) return packAliasMatch;
    }
  }
  const lower = name.toLowerCase();
  for (const [key, trans] of Object.entries(productNames)) {
    if (lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) {
      return trans[lang] || name;
    }
  }
  for (const [alias, master] of Object.entries(productAliases)) {
    if (lower.includes(alias.toLowerCase()) || alias.toLowerCase().includes(lower)) {
      const t = productNames[master]?.[lang];
      if (t) return t;
    }
  }
  return name;
}
